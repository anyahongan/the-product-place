export function draftForContact(
  contact: NetworkContact,
  kind: OutreachDraft["kind"] = "COLD OUTREACH",
  format?: CommunicationFormatPreference | null,
  applications: { applicationId: string; title: string; companyId: string }[] = networkApplications.map(
    (a) => ({ applicationId: a.id, title: a.role, companyId: a.companyId }),
  ),
): OutreachDraft {
  const company = networkCompanies.find((c) => c.id === contact.companyId)?.name ?? "the company";
  const firstName = contact.name.split(" ")[0] ?? contact.name;
  const role =
    applications.find((a) => contact.relatedApplicationIds.includes(a.applicationId))?.title ??
    "a product internship";
  const reason =
    contact.isCampusRecruiter || contact.contactType === "CAMPUS RECRUITER"
      ? `you lead campus recruiting for product at ${company}`
      : contact.isRecruiter
        ? `you recruit for product roles at ${company}`
        : contact.contactType === "PRODUCT MANAGER"
          ? `of your product work at ${company}`
          : contact.schoolRelationship?.toLowerCase().includes("alum")
            ? `you are a Stanford alum on the ${company} team`
            : contact.contactType === "FORMER INTERN"
              ? `you were a former intern at ${company}`
              : `of your role as ${contact.title} at ${company}`;

  if (format?.mode === "template" && format.template) {
    const filled = format.template
      .replaceAll("[First Name]", firstName)
      .replaceAll("[Company]", company)
      .replaceAll("[Role]", role)
      .replaceAll("[Your Name]", "Anya")
      .replaceAll("[Major]", "Symbolic Systems")
      .replaceAll("[School]", "Stanford")
      .replaceAll("[Field]", "product management")
      .replaceAll("[Specific Reason]", reason);
    const subjectPrefix =
      kind === "FOLLOW-UP"
        ? "Following up"
        : kind === "THANK-YOU"
          ? "Thank you"
          : kind === "REFERRAL FOLLOW-UP"
            ? "Referral next steps"
            : "Introduction";
    return {
      kind,
      to: contact.name,
      subject: `${subjectPrefix}: ${company}`,
      body: filled,
    };
  }

  if (kind === "FOLLOW-UP") {
    return {
      kind,
      to: contact.name,
      subject: `Following up: ${company}`,
      body: `Hi ${firstName},\n\nI hope you are having a good day. I wanted to follow up on my note from last week about the product internship at ${company}. I remain very interested and would appreciate any guidance you can share, or a brief conversation if your schedule allows.\n\nThank you for your time,\nAnya`,
    };
  }
  if (kind === "THANK-YOU") {
    return {
      kind,
      to: contact.name,
      subject: `Thank you for our conversation about ${company}`,
      body: `Hi ${firstName},\n\nI hope you are having a good day. Thank you for taking the time to speak with me. I especially appreciated what you shared about the team, and I will incorporate that into my application materials.\n\nBest regards,\nAnya`,
    };
  }
  if (kind === "REFERRAL FOLLOW-UP") {
    return {
      kind,
      to: contact.name,
      subject: `Referral next steps at ${company}`,
      body: `Hi ${firstName},\n\nI hope you are having a good day. Checking in on the referral we discussed for the product internship at ${company}. Please let me know if any materials would make this easier on your side.\n\nThank you again,\nAnya`,
    };
  }
  return {
    kind: "COLD OUTREACH",
    to: contact.name,
    subject: `${company} product internship introduction`,
    body: `Hi ${firstName},\n\nI hope you are having a good day. My name is Anya, and I am a Symbolic Systems student at Stanford interested in product management. I wanted to reach out to you because ${reason}. I am preparing an application for a product internship at ${company} and would value 15 minutes to learn how you think about the role and what makes a strong intern candidate.\n\nThank you for considering,\nAnya`,
  };
}

export function formatNetworkDate(iso: string): string {
  const d = new Date(`${iso}T12:00:00`);
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric" });
}
